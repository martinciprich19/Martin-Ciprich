import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const migration = file => readFile(new URL(file, import.meta.url), 'utf8')

test('signup trigger repairs numeric profiles while preserving registration metadata and atomic failures', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      create role anon; create role authenticated;
      create schema auth;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
      create table public.arenas(id bigint primary key, region text);
      create table public.proffiles(
        id bigint generated by default as identity primary key,
        created_at timestamptz not null default now(), full_name text, email text unique,
        phone text, elo_rating integer default 1000, highest_elo integer default 1300,
        matches_played integer, matches_won integer default 0,
        region text, level text, dominant_hand text, home_venue_id bigint references public.arenas(id),
        auto_venue_id bigint, gender text, starting_elo integer not null default 1000,
        career_elo integer not null default 1000
      );
      create table public.pairs(id bigint primary key);
      create table public.challenges(id bigint primary key);
      create table public.matches(id bigint primary key);
      create table public.live_matches(id bigint primary key);
      insert into public.arenas values (10, 'Trenčiansky kraj');
      create function public.handle_new_user() returns trigger language plpgsql security definer as $$
      begin
        insert into public.proffiles(id,email,full_name,qr_code,created_at)
        values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name','Nový Hráč'),
          'RIVA-' || substring(new.id::text from 1 for 8),now()) on conflict(id) do nothing;
        return new;
      end $$;
      create trigger on_auth_user_created after insert on auth.users
        for each row execute function public.handle_new_user();
    `)
    await db.exec(await migration('028_profile_gender.sql'))
    await db.exec(await migration('068_national_leagues.sql'))
    const routing = await migration('069_national_league_routing.sql')
    await db.exec(routing.slice(
      routing.indexOf('create or replace function public.guard_profile_national_membership()'),
      routing.indexOf('create or replace function public.route_national_league_row()'),
    ))
    const insertUser = (id, email, metadata) => db.query(
      'insert into auth.users(id,email,raw_user_meta_data) values($1,$2,$3::jsonb)',
      [id, email, JSON.stringify(metadata)])
    const id = '11111111-1111-4111-8111-111111111111'
    const slovak = { full_name: 'Test Player', display_name: 'Test Player',
      country_code: 'SK', preferred_language: 'sk', subdivision_code: 'SK-TC',
      region: 'Trenčiansky kraj', level: 'Začiatočník', dominant_hand: 'left',
      gender: 'male', home_venue_id: '10' }
    await assert.rejects(insertUser(id, 'test@example.invalid', slovak), /qr_code/)
    assert.equal((await db.query('select count(*)::int as n from auth.users')).rows[0].n, 0)
    await db.exec(await migration('092_repair_signup_profile.sql'))
    await db.exec(await migration('092_repair_signup_profile.sql'))
    await insertUser(id, 'test@example.invalid', slovak)
    assert.deepEqual((await db.query(`select id,full_name,email,region,level,dominant_hand,gender,
      country_code,preferred_language,subdivision_code,home_venue_id,elo_rating,highest_elo,
      starting_elo,career_elo,matches_played,matches_won from public.proffiles`)).rows[0], {
      id: 1, full_name: 'Test Player', email: 'test@example.invalid',
      region: 'Trenčiansky kraj', level: 'Začiatočník', dominant_hand: 'left', gender: 'male',
      country_code: 'SK', preferred_language: 'sk', subdivision_code: 'SK-TC',
      home_venue_id: 10, elo_rating: 1000, highest_elo: 1000,
      starting_elo: 1000, career_elo: 1000, matches_played: 0, matches_won: 0,
    })
    await insertUser('22222222-2222-4222-8222-222222222222', 'nl@example.invalid', {
      full_name: 'Dutch Player', country_code: 'NL', preferred_language: 'en',
      subdivision_code: 'NL-NH', region: 'Noord-Holland', gender: 'female', dominant_hand: 'right',
    })
    assert.deepEqual((await db.query(`select country_code,preferred_language,subdivision_code,region,gender
      from proffiles where email='nl@example.invalid'`)).rows[0], {
      country_code: 'NL', preferred_language: 'en', subdivision_code: 'NL-NH',
      region: 'Noord-Holland', gender: 'female',
    })
    await assert.rejects(insertUser('33333333-3333-4333-8333-333333333333', 'bad@example.invalid', {
      country_code: 'NL', preferred_language: 'nl', subdivision_code: 'NL-NH', home_venue_id: '10',
    }), /Home arena/)
    await assert.rejects(insertUser('44444444-4444-4444-8444-444444444444', 'TEST@example.invalid', slovak), /už existuje/)
    assert.equal((await db.query('select count(*)::int as n from auth.users')).rows[0].n, 2)
    assert.equal((await db.query('select count(*)::int as n from proffiles')).rows[0].n, 2)
    await db.exec('set role anon')
    await assert.rejects(db.exec('select public.handle_new_user()'), /permission denied/)
  } finally { await db.close() }
})
