begin;

do $repair$
begin
  if to_regclass('public.pair_invitations') is not null
    and exists (
      select 1 from information_schema.columns
      where table_schema = 'public'
        and table_name = 'pair_invitations'
        and column_name = 'id'
        and data_type = 'uuid'
    ) then
    if to_regclass('public.pair_invitations_uuid_backup') is not null then
      raise exception 'Záloha pair_invitations_uuid_backup už existuje. Oprava bola zastavená bez prepísania dát.';
    end if;
    if not exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'pair_invitations'
        and column_name = 'sender_id' and data_type = 'uuid'
    ) or not exists (
      select 1 from information_schema.columns
      where table_schema = 'public' and table_name = 'pair_invitations'
        and column_name = 'receiver_id' and data_type = 'uuid'
    ) then
      raise exception 'Neočekávaná štruktúra UUID pozvánok. Oprava bola zastavená.';
    end if;

    lock table public.pair_invitations in access exclusive mode;
    alter table public.pair_invitations rename to pair_invitations_uuid_backup;
    revoke all on public.pair_invitations_uuid_backup from public, anon, authenticated;
    alter table public.pair_invitations_uuid_backup enable row level security;
  end if;
end;
$repair$;

create table if not exists public.pair_invitations (
  id bigint generated by default as identity primary key,
  inviter_id bigint not null references public.proffiles(id) on delete cascade,
  invitee_id bigint not null references public.proffiles(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now(),
  legacy_invitation_id uuid unique,
  check (inviter_id <> invitee_id)
);

alter table public.pair_invitations
  add column if not exists legacy_invitation_id uuid;
create unique index if not exists pair_invitations_legacy_uuid_v2_idx
  on public.pair_invitations (legacy_invitation_id);

do $transfer$
begin
  if to_regclass('public.pair_invitations_uuid_backup') is null then
    return;
  end if;

  if exists (
    select 1
    from public.pair_invitations_uuid_backup as invitation
    where (
      select count(*)
      from auth.users as account
      join public.proffiles as profile
        on lower(profile.email) = lower(account.email)
      where account.id = invitation.sender_id
    ) <> 1 or (
      select count(*)
      from auth.users as account
      join public.proffiles as profile
        on lower(profile.email) = lower(account.email)
      where account.id = invitation.receiver_id
    ) <> 1
  ) then
    raise exception 'Niektoré staré pozvánky nemajú jednoznačný profil odosielateľa alebo príjemcu. Žiadne zmeny neboli uložené.';
  end if;

  if exists (
    select 1 from public.pair_invitations_uuid_backup
    where status is null
      or status not in ('pending', 'accepted', 'declined')
  ) then
    raise exception 'Staré pozvánky obsahujú neočakávaný status. Žiadne zmeny neboli uložené.';
  end if;

  insert into public.pair_invitations (
    inviter_id, invitee_id, status, created_at, legacy_invitation_id
  )
  select sender.id, receiver.id, invitation.status,
    coalesce(invitation.created_at, now()), invitation.id
  from public.pair_invitations_uuid_backup as invitation
  join auth.users as sender_account on sender_account.id = invitation.sender_id
  join auth.users as receiver_account on receiver_account.id = invitation.receiver_id
  join public.proffiles as sender on lower(sender.email) = lower(sender_account.email)
  join public.proffiles as receiver on lower(receiver.email) = lower(receiver_account.email)
  where not exists (
    select 1 from public.pair_invitations as migrated
    where migrated.legacy_invitation_id = invitation.id
  );
end;
$transfer$;

create index if not exists pair_invitations_recipient_status_v2_idx
  on public.pair_invitations (invitee_id, status, created_at desc);
create unique index if not exists pair_invitations_pending_members_v2_idx
  on public.pair_invitations (
    least(inviter_id, invitee_id), greatest(inviter_id, invitee_id)
  ) where status = 'pending';

alter table public.pair_invitations enable row level security;
revoke all on public.pair_invitations from public, anon, authenticated;
grant select on public.pair_invitations to authenticated;
revoke insert on public.pairs from anon, authenticated;

drop policy if exists "pair invitation participants can read"
  on public.pair_invitations;
create policy "pair invitation participants can read"
  on public.pair_invitations for select to authenticated
  using (
    exists (
      select 1 from public.proffiles as profile
      where profile.id in (inviter_id, invitee_id)
        and lower(profile.email) = lower(auth.jwt() ->> 'email')
    )
  );

-- PostgreSQL cannot replace a UUID-returning function with a bigint return type.
drop function if exists public.create_pair_invitation(bigint);
create or replace function public.create_pair_invitation(p_invitee_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $function$
declare
  current_profile_id bigint;
  invitation_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Prihlásenie je potrebné na pozvanie do dvojice.';
  end if;
  select id into current_profile_id from public.proffiles
  where lower(email) = lower(auth.jwt() ->> 'email') limit 1;
  if current_profile_id is null then
    raise exception 'Profil prihláseného používateľa sa nenašiel.';
  end if;
  if p_invitee_id is null or p_invitee_id = current_profile_id then
    raise exception 'Vyber iného hráča.';
  end if;
  if not exists (
    select 1 from public.friendships
    where status = 'accepted' and (
      (user_id = current_profile_id and friend_id = p_invitee_id)
      or (user_id = p_invitee_id and friend_id = current_profile_id)
    )
  ) then
    raise exception 'Pozvať do dvojice môžeš iba prijatého priateľa.';
  end if;
  if exists (
    select 1 from public.pairs
    where (player_1_id = current_profile_id and player_2_id = p_invitee_id)
      or (player_1_id = p_invitee_id and player_2_id = current_profile_id)
  ) then
    raise exception 'Títo hráči už tvoria dvojicu.';
  end if;
  insert into public.pair_invitations (inviter_id, invitee_id)
  values (current_profile_id, p_invitee_id)
  returning id into invitation_id;
  return invitation_id;
end;
$function$;

drop function if exists public.respond_to_pair_invitation(bigint, boolean);
create or replace function public.respond_to_pair_invitation(
  p_invitation_id bigint, p_accept boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $function$
declare
  current_profile_id bigint;
  invitation_inviter_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Prihlásenie je potrebné na odpoveď na pozvanie.';
  end if;
  if p_accept is null then
    raise exception 'Vyber prijatie alebo odmietnutie pozvánky.';
  end if;
  select id into current_profile_id from public.proffiles
  where lower(email) = lower(auth.jwt() ->> 'email') limit 1;
  if current_profile_id is null then
    raise exception 'Profil prihláseného používateľa sa nenašiel.';
  end if;
  select inviter_id into invitation_inviter_id
  from public.pair_invitations
  where id = p_invitation_id and invitee_id = current_profile_id
    and status = 'pending'
  for update;
  if invitation_inviter_id is null then
    raise exception 'Čakajúce pozvanie sa nenašlo.';
  end if;
  if not p_accept then
    update public.pair_invitations set status = 'declined'
    where id = p_invitation_id;
    return;
  end if;
  if not exists (
    select 1 from public.friendships
    where status = 'accepted' and (
      (user_id = current_profile_id and friend_id = invitation_inviter_id)
      or (user_id = invitation_inviter_id and friend_id = current_profile_id)
    )
  ) then
    raise exception 'Dvojicu môžu vytvoriť iba prijatí priatelia.';
  end if;
  if exists (
    select 1 from public.pairs
    where (player_1_id = current_profile_id and player_2_id = invitation_inviter_id)
      or (player_1_id = invitation_inviter_id and player_2_id = current_profile_id)
  ) then
    raise exception 'Títo hráči už tvoria dvojicu.';
  end if;
  insert into public.pairs (player_1_id, player_2_id, created_by)
  values (invitation_inviter_id, current_profile_id, current_profile_id);
  update public.pair_invitations set status = 'accepted'
  where id = p_invitation_id;
end;
$function$;

revoke all on function public.create_pair_invitation(bigint) from public, anon;
revoke all on function public.respond_to_pair_invitation(bigint, boolean) from public, anon;
grant execute on function public.create_pair_invitation(bigint) to authenticated;
grant execute on function public.respond_to_pair_invitation(bigint, boolean) to authenticated;

do $realtime$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public'
        and tablename = 'pair_invitations_uuid_backup'
    ) then
      alter publication supabase_realtime
        drop table public.pair_invitations_uuid_backup;
    end if;
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public'
        and tablename = 'pair_invitations'
    ) then
      alter publication supabase_realtime add table public.pair_invitations;
    end if;
  end if;
end;
$realtime$;

notify pgrst, 'reload schema';
