import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const migration = await readFile(new URL('079_super_admin_console.sql', import.meta.url), 'utf8')
const superAdmin = '00000000-0000-0000-0000-000000000091'
const arenaManager = '00000000-0000-0000-0000-000000000092'
const kioskId = '00000000-0000-0000-0000-000000000093'

test('Super Admin RPCs create auditable global actions and reject other roles', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create schema auth;
      create table auth.users(id uuid primary key, email text);
      insert into auth.users values
        ('${superAdmin}', 'owner@example.test'),
        ('${arenaManager}', 'manager@example.test');
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
      $$;
      create function auth.jwt() returns jsonb language sql stable as $$
        select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb);
      $$;

      create table public.arenas (
        id bigint generated by default as identity primary key,
        name text not null, city text not null, address text not null,
        region text not null, country_code text not null, subdivision_code text,
        courts_count integer, is_active boolean not null default true
      );
      create table public.arena_admins (
        arena_id bigint not null references public.arenas(id) on delete cascade,
        user_id uuid not null references auth.users(id) on delete cascade,
        created_at timestamptz not null default now(),
        primary key (arena_id, user_id)
      );
      create table public.arena_kiosk_devices (
        id uuid primary key, arena_id bigint not null references public.arenas(id),
        name text not null, token_hash text not null unique,
        authorized_by uuid not null references auth.users(id),
        created_at timestamptz not null default now(), revoked_at timestamptz
      );
      create table public.notifications (
        id uuid primary key default gen_random_uuid(), user_id bigint not null,
        type text not null, title text, body text, message text, is_read boolean not null default false
      );
      alter table public.notifications enable row level security;
      alter table public.arena_kiosk_devices enable row level security;
      grant select on public.arenas, public.notifications to authenticated;
    `)
    await db.exec(migration)

    await db.exec(`set role authenticated;
      set request.jwt.claim.sub = '${superAdmin}';
      set request.jwt.claims = '{"app_metadata":{"role":"super_admin"}}';`)
    const arenaId = (await db.query(
      `select public.super_admin_create_arena($1, $2, $3, $4, $5, $6) as id`,
      ['Riva Padel', 'Bratislava', 'Testovacia 1', 'SK', 'Bratislavský kraj', 4],
    )).rows[0].id
    assert.equal((await db.query('select name, courts_count from public.arenas where id = $1', [arenaId])).rows[0].courts_count, 4)
    assert.equal((await db.query('select action from public.super_admin_audit_log')).rows[0].action, 'arena.created')

    await db.query('select public.super_admin_assign_arena_manager($1, $2)', [arenaId, 'manager@example.test'])
    assert.equal((await db.query('select email from public.super_admin_list_arena_managers()')).rows[0].email, 'manager@example.test')
    await db.query('select public.super_admin_set_arena_active($1, false)', [arenaId])
    assert.equal((await db.query('select is_active from public.arenas where id = $1', [arenaId])).rows[0].is_active, false)

    await db.exec('reset role')
    await db.query(
      `insert into public.arena_kiosk_devices(id, arena_id, name, token_hash, authorized_by)
       values ($1, $2, 'Tablet', 'private-hash', $3)`,
      [kioskId, arenaId, superAdmin],
    )
    await db.exec('set role authenticated')
    await assert.rejects(db.query('select token_hash from public.arena_kiosk_devices'), /permission denied/)
    await db.query('select public.super_admin_revoke_kiosk_device($1)', [kioskId])
    assert.ok((await db.query('select revoked_at from public.arena_kiosk_devices where id = $1', [kioskId])).rows[0].revoked_at)

    await db.query('select public.super_admin_send_announcement($1, $2)', ['Údržba', 'O 23:00'])
    const notice = (await db.query('select user_id, type, title from public.notifications')).rows[0]
    assert.equal(notice.user_id, null)
    assert.equal(notice.type, 'system_announcement')
    assert.equal(notice.title, 'Údržba')
    assert.equal((await db.query('select count(*)::int as count from public.super_admin_audit_log')).rows[0].count, 5)

    await db.exec(`set request.jwt.claim.sub = '${arenaManager}';
      set request.jwt.claims = '{"app_metadata":{"role":"admin"}}';`)
    assert.equal((await db.query('select count(*)::int as count from public.notifications')).rows[0].count, 1)
    await assert.rejects(
      db.query('select public.super_admin_send_announcement($1, $2)', ['Neoprávnené', 'Zlyhanie']),
      /Super Admin access required/,
    )
    await assert.rejects(
      db.query("insert into public.super_admin_audit_log(actor_id, action, target_type) values ($1, 'forged', 'arena')", [arenaManager]),
      /permission denied/,
    )
    await assert.rejects(db.query('update public.super_admin_audit_log set action = $1', ['forged']), /permission denied/)
  } finally {
    await db.close()
  }
})
