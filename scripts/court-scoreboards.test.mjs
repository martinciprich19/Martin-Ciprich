import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const migration = readFileSync(new URL('./072_court_scoreboards.sql', import.meta.url), 'utf8')
const sponsorMigration = readFileSync(new URL('./073_arena_sponsor_ads.sql', import.meta.url), 'utf8')
const managerId = '10000000-0000-0000-0000-000000000001'

async function fixture(includeSponsors = false) {
  const db = new PGlite()
  await db.exec(`
    create role anon;
    create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    create table public.arenas(id bigint primary key, name text, country_code text, is_active boolean);
    create table public.arena_courts(id bigint primary key, arena_id bigint references public.arenas(id), name text, is_active boolean);
    create table public.challenges(id bigint primary key, arena_id bigint);
    create table public.live_matches(
      id uuid primary key,
      challenge_id text,
      country_code text,
      court_id bigint references public.arena_courts(id),
      team_a_player1_name text,
      team_a_player2_name text,
      team_b_player1_name text,
      team_b_player2_name text,
      team_a_game_score smallint,
      team_b_game_score smallint,
      advantage_team text,
      tiebreak_score jsonb,
      team_a_games integer,
      team_b_games integer,
      team_a_sets integer,
      team_b_sets integer,
      started_at timestamptz,
      initial_server_chosen boolean,
      finished_at timestamptz,
      ended_early_at timestamptz,
      paused_at timestamptz,
      is_pin_activated boolean,
      match_pin text
    );
    create function public.activate_live_match_pin_with_settings(text,text,text,text)
    returns uuid language sql as $$ select '10000000-0000-0000-0000-000000000001'::uuid $$;
    insert into public.arenas values (10, 'Arena', 'SK', true), (11, 'Other', 'NL', true);
    insert into public.arena_courts values (20, 10, 'Court 1', true), (21, 11, 'Court 2', true);
    insert into public.challenges values (30, 10);
    insert into public.live_matches values (
      '10000000-0000-0000-0000-000000000001', '30', 'SK', null,
      'A1', 'A2', 'B1', 'B2', 15, 30, null, null, 2, 1, 0, 0,
      now(), true, null, null, null, true, '1234'
    );
  `)
  await db.exec(migration)
  if (includeSponsors) {
    await db.exec(`
      create table public.arena_admins(arena_id bigint, user_id uuid);
      insert into public.arena_admins values (10, '${managerId}');
      create function public.is_arena_admin(p_arena_id bigint)
      returns boolean language sql stable security definer set search_path = '' as $$
        select auth.uid() = '${managerId}'::uuid and p_arena_id = 10
      $$;
      grant execute on function public.is_arena_admin(bigint) to authenticated;
      create schema storage;
      create table storage.buckets(
        id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]
      );
      create table storage.objects(id bigint generated by default as identity, bucket_id text, name text);
      alter table storage.objects enable row level security;
      create function storage.foldername(path text) returns text[]
      language sql immutable as $$ select string_to_array(path, '/') $$;
      grant usage on schema storage to anon, authenticated;
      grant select, insert, update, delete on storage.objects to anon, authenticated;
    `)
    await db.exec(sponsorMigration)
  }
  return db
}

test('court pin activation stores selected court and refuses a challenge for another arena', async () => {
  const db = await fixture()
  try {
    const activated = await db.query(`
      select public.activate_live_match_pin_for_court('1234','golden_point','standard','full_set',20) as id
    `)
    assert.equal(activated.rows[0].id, '10000000-0000-0000-0000-000000000001')
    assert.equal((await db.query('select court_id from public.live_matches')).rows[0].court_id, 20)
    await assert.rejects(
      db.query(`select public.activate_live_match_pin_for_court('5678','golden_point','standard','full_set',21)`),
      /vybraného kurtu|different arena|inna arénu|country/i,
    )
  } finally {
    await db.close()
  }
})

test('public scoreboard returns only the active game assigned to the requested active court', async () => {
  const db = await fixture(true)
  try {
    await db.query("update public.live_matches set court_id = 20")
    const result = await db.query('select * from public.get_court_scoreboard(20)')
    assert.equal(result.rows.length, 1)
    assert.equal(result.rows[0].court_name, 'Court 1')
    assert.equal(result.rows[0].arena_id, 10)
    assert.equal(result.rows[0].team_a_game_score, 15)
    assert.equal((await db.query('select * from public.get_court_scoreboard(21)')).rows[0].match_id, null)
    await db.query('update public.live_matches set paused_at = now()')
    assert.ok((await db.query('select * from public.get_court_scoreboard(20)')).rows[0].paused_at)
  } finally {
    await db.close()
  }
})

test('sponsor ads are public only while active and only assigned arena managers may manage them', async () => {
  const db = await fixture(true)
  try {
    await db.exec(sponsorMigration)
    await db.exec(`
      set request.jwt.claim.sub = '${managerId}';
      set role authenticated;
      insert into public.arena_sponsor_ads(arena_id, sponsor_name, image_path, is_active)
      values (10, 'Local Sponsor', '10/logo.png', true);
      insert into public.arena_sponsor_ads(arena_id, sponsor_name, image_path, is_active)
      values (10, 'Paused Sponsor', '10/paused.png', false);
    `)
    assert.equal((await db.query('select count(*)::int as count from public.arena_sponsor_ads')).rows[0].count, 2)
    await db.exec(`
      insert into storage.objects(bucket_id, name) values ('arena-sponsor-ads', '10/logo.png');
    `)
    await assert.rejects(
      db.exec("insert into storage.objects(bucket_id, name) values ('arena-sponsor-ads', '11/logo.png')"),
      /row-level security/i,
    )
    await assert.rejects(
      db.exec("insert into storage.objects(bucket_id, name) values ('arena-sponsor-ads', 'not-an-arena/logo.png')"),
      /row-level security/i,
    )
    await assert.rejects(
      db.exec("insert into public.arena_sponsor_ads(arena_id, sponsor_name, image_path) values (11, 'Other', '11/logo.png')"),
      /row-level security/i,
    )
    await assert.rejects(
      db.exec("insert into public.arena_sponsor_ads(arena_id, sponsor_name, image_path) values (10, 'Wrong path', '11/logo.png')"),
      /row-level security|check constraint/i,
    )
    await db.exec('reset role; set role anon;')
    assert.equal((await db.query('select count(*)::int as count from public.arena_sponsor_ads')).rows[0].count, 1)
    await db.exec('reset role')
  } finally {
    await db.close()
  }
})
