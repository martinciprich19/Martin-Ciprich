-- Apply the entire file in the Supabase SQL Editor after migration 070.
-- Arena managers are assigned to existing auth users by an owner; this does not
-- grant the global app_metadata role or allow managers to assign themselves.
begin;

do $$
begin
  if to_regclass('public.arenas') is null then
    raise exception 'Missing required table public.arenas.';
  end if;
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'arenas'
      and column_name = 'id'
      and data_type = 'bigint'
  ) then
    raise exception 'Expected public.arenas.id to be bigint.';
  end if;
end;
$$;

create table if not exists public.arena_admins (
  arena_id bigint not null references public.arenas(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (arena_id, user_id)
);

alter table public.arena_admins enable row level security;
revoke all on public.arena_admins from public, anon, authenticated;
grant select on public.arena_admins to authenticated;

drop policy if exists arena_admins_read_own on public.arena_admins;
create policy arena_admins_read_own
  on public.arena_admins for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.is_arena_admin(p_arena_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null and exists (
    select 1
    from public.arena_admins manager
    where manager.arena_id = p_arena_id
      and manager.user_id = auth.uid()
  );
$$;

revoke all on function public.is_arena_admin(bigint) from public, anon;
grant execute on function public.is_arena_admin(bigint) to authenticated;

-- Assigned managers can still access their arena if it is temporarily inactive.
drop policy if exists arenas_assigned_manager_read on public.arenas;
create policy arenas_assigned_manager_read
  on public.arenas for select to authenticated
  using ((select public.is_arena_admin(id)));

create table if not exists public.arena_courts (
  id bigint generated by default as identity primary key,
  arena_id bigint not null references public.arenas(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 80),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (arena_id, name)
);

create index if not exists arena_courts_arena_sort_idx
  on public.arena_courts (arena_id, sort_order, id);

alter table public.arena_courts enable row level security;
revoke all on public.arena_courts from public, anon, authenticated;
grant select, insert, update on public.arena_courts to authenticated;

drop policy if exists arena_courts_manager_access on public.arena_courts;
create policy arena_courts_manager_access
  on public.arena_courts for all to authenticated
  using ((select public.is_arena_admin(arena_id)))
  with check ((select public.is_arena_admin(arena_id)));

notify pgrst, 'reload schema';
commit;
